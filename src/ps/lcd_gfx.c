/******************************************************************************
 * lcd_gfx.c - 800x480 RGB565 TFT-LCD 绘图库实现
 *
 * 像素格式(必须与工程一致):
 *   每像素 3 字节 { byte0 = RGB565低8位, byte1 = RGB565高8位, byte2 = 0x00 }
 *   坐标: x=[0,WIDTH) 向右, y=[0,HEIGHT) 向下。
 *
 * 字库: public domain 8x8 字体 (Daniel Hepper / Marcel Sondaar / IBM VGA),
 *       覆盖 ASCII 0x20~0x7E。如需中文, 需自行增加点阵数组并扩展 lcd_char。
 ******************************************************************************/
#include "lcd_gfx.h"
#include "xil_cache.h"
#include <string.h>

/* ================= 内部小工具 ================= */

/* "保护色": 非 0 时 px_put 不覆盖已经是该颜色的像素。
   用途: 画第二路波形时保护第一路 —— 两路交叉处否则会把先画的那路割出 1 像素缺口,
   看起来像波形"错开/断开"。 */
static u16 lcd_protect;

void lcd_set_protect(u16 color)
{
    lcd_protect = color;
}

/* 写一个像素(自动裁剪, 越界直接忽略) */
static void px_put(u32 fb, int x, int y, u16 c)
{
    u8 *p;
    if (((u32)x >= (u32)LCD_GFX_WIDTH) || ((u32)y >= (u32)LCD_GFX_HEIGHT)) {
        return;
    }
    p = (u8 *)(fb + (((u32)y * (u32)LCD_GFX_WIDTH + (u32)x) * 3u));
    if (lcd_protect != 0u) {
        u16 cur = (u16)((u16)p[0] | ((u16)p[1] << 8));
        if (cur == lcd_protect) {
            return;                      /* 这一像素属于被保护的通道, 不覆盖 */
        }
    }
    p[0] = (u8)(c & 0xFFu);
    p[1] = (u8)(c >> 8);
    p[2] = 0x00;
}

/* 整数开方(floor), 牛顿迭代 */
static u32 isqrt_u32(u32 n)
{
    u32 x, y;
    if (n < 2u) {
        return n;
    }
    x = n;
    y = (x + 1u) >> 1;
    while (y < x) {
        x = y;
        y = (x + n / x) >> 1;
    }
    return x;
}

/* 椭圆在竖直偏移 dy 处的半宽(近似, 用于行扫描) */
static s32 half_w(s32 rx, s32 ry, s32 dy)
{
    u64 ry2, num;
    if (ry == 0) {
        return rx;
    }
    ry2 = (u64)((s64)ry * (s64)ry);
    if ((u64)((s64)dy * (s64)dy) >= ry2) {
        return 0;
    }
    /* x = rx * sqrt(1 - dy^2/ry^2) 的整数化 */
    num = (u64)((s64)rx * (s64)rx) * (ry2 - (u64)((s64)dy * (s64)dy));
    return (s32)isqrt_u32((u32)(num / ry2));
}

/* 饱和: s64 -> s32 安全钳位 */
static s32 sat_s64(s64 v)
{
    if (v > 0x7FFFFFFFLL) {
        return 0x7FFFFFFF;
    }
    if (v < -0x7FFFFFFFLL - 1LL) {
        return -0x7FFFFFFF - 1;
    }
    return (s32)v;
}

/* ================= 公共接口 ================= */

u16 lcd_rgb565(u8 r, u8 g, u8 b)
{
    u32 r5 = ((u32)r * 31u + 127u) / 255u;
    u32 g6 = ((u32)g * 63u + 127u) / 255u;
    u32 b5 = ((u32)b * 31u + 127u) / 255u;
    return (u16)((r5 << 11) | (g6 << 5) | b5);
}

void lcd_clear(u32 fb, u16 color)
{
    u8  *p = (u8 *)fb;
    u8   lo = (u8)(color & 0xFFu);
    u8   hi = (u8)(color >> 8);
    u32  i;

    for (i = 0; i < LCD_GFX_FRAME_BYTES; i += 3u) {
        p[i]     = lo;
        p[i + 1] = hi;
        p[i + 2] = 0x00;
    }
}

void lcd_flush(u32 fb)
{
    Xil_DCacheFlushRange((UINTPTR)fb, LCD_GFX_FRAME_BYTES);
}

void lcd_pixel(u32 fb, int x, int y, u16 color)
{
    px_put(fb, x, y, color);
}

void lcd_hline(u32 fb, int x0, int x1, int y, u16 color)
{
    int t;
    if (((u32)y >= (u32)LCD_GFX_HEIGHT)) {
        return;
    }
    if (x0 > x1) {
        t = x0; x0 = x1; x1 = t;
    }
    if (x1 < 0 || x0 >= (int)LCD_GFX_WIDTH) {
        return;
    }
    if (x0 < 0) {
        x0 = 0;
    }
    if (x1 >= (int)LCD_GFX_WIDTH) {
        x1 = (int)LCD_GFX_WIDTH - 1;
    }
    for (; x0 <= x1; x0++) {
        px_put(fb, x0, y, color);
    }
}

void lcd_vline(u32 fb, int x, int y0, int y1, u16 color)
{
    int t;
    if (((u32)x >= (u32)LCD_GFX_WIDTH)) {
        return;
    }
    if (y0 > y1) {
        t = y0; y0 = y1; y1 = t;
    }
    if (y1 < 0 || y0 >= (int)LCD_GFX_HEIGHT) {
        return;
    }
    if (y0 < 0) {
        y0 = 0;
    }
    if (y1 >= (int)LCD_GFX_HEIGHT) {
        y1 = (int)LCD_GFX_HEIGHT - 1;
    }
    for (; y0 <= y1; y0++) {
        px_put(fb, x, y0, color);
    }
}

/* Bresenham 直线 */
void lcd_line(u32 fb, int x0, int y0, int x1, int y1, u16 color)
{
    int dx, dy, sx, sy, err, e2;

    dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    sx = (x0 < x1) ? 1 : -1;
    sy = (y0 < y1) ? 1 : -1;
    err = dx - dy;

    for (;;) {
        px_put(fb, x0, y0, color);
        if (x0 == x1 && y0 == y1) {
            break;
        }
        e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 < dx)  { err += dx; y0 += sy; }
    }
}

void lcd_rect(u32 fb, int x, int y, int w, int h, u16 color)
{
    if (w <= 0 || h <= 0) {
        return;
    }
    lcd_hline(fb, x, x + w - 1, y, color);
    lcd_hline(fb, x, x + w - 1, y + h - 1, color);
    lcd_vline(fb, x, y, y + h - 1, color);
    lcd_vline(fb, x + w - 1, y, y + h - 1, color);
}

void lcd_fill_rect(u32 fb, int x, int y, int w, int h, u16 color)
{
    int yy;
    if (w <= 0 || h <= 0) {
        return;
    }
    for (yy = y; yy < y + h; yy++) {
        lcd_hline(fb, x, x + w - 1, yy, color);
    }
}

/* 椭圆空心: 用"行扫描+列扫描"两个方向的对称点保证边界连续 */
void lcd_ellipse(u32 fb, int cx, int cy, int rx, int ry, u16 color)
{
    s32 a = (rx < 0) ? -rx : rx;
    s32 b = (ry < 0) ? -ry : ry;
    s32 i, d;

    for (i = -b; i <= b; i++) {
        d = half_w(a, b, i);
        px_put(fb, cx + d, cy + i, color);
        px_put(fb, cx - d, cy + i, color);
    }
    for (i = -a; i <= a; i++) {
        d = half_w(b, a, i);   /* 交换角色: 求列方向高度 */
        px_put(fb, cx + i, cy + d, color);
        px_put(fb, cx + i, cy - d, color);
    }
}

void lcd_fill_ellipse(u32 fb, int cx, int cy, int rx, int ry, u16 color)
{
    s32 a = (rx < 0) ? -rx : rx;
    s32 b = (ry < 0) ? -ry : ry;
    s32 i, d;

    if (a == 0 && b == 0) {
        px_put(fb, cx, cy, color);
        return;
    }
    for (i = -b; i <= b; i++) {
        d = half_w(a, b, i);
        lcd_hline(fb, cx - d, cx + d, cy + i, color);
    }
}

void lcd_circle(u32 fb, int cx, int cy, int r, u16 color)
{
    lcd_ellipse(fb, cx, cy, r, r, color);
}

void lcd_fill_circle(u32 fb, int cx, int cy, int r, u16 color)
{
    lcd_fill_ellipse(fb, cx, cy, r, r, color);
}

/* 1bpp 掩码位图: 只写掩码里为 1 的像素, 为 0 的像素一个字节都不碰 ——
   所以底下的背景色块和按钮边框会原样保留, 适合画"细描边"图标(齿轮/箭头等)。
   掩码按行存放, 每行 (w+7)/8 字节, 每字节 MSB 在最左边。不依赖任何图片资源。 */
void lcd_blit_mask(u32 fb, int x, int y, int w, int h, const u8 *mask, u16 color)
{
    int i, j, stride;

    if ((mask == 0) || (w <= 0) || (h <= 0)) {
        return;
    }
    stride = (w + 7) / 8;
    for (j = 0; j < h; j++) {
        for (i = 0; i < w; i++) {
            u8 b = mask[(u32)j * (u32)stride + (u32)(i >> 3)];
            if ((b & (u8)(0x80u >> (i & 7))) != 0u) {
                px_put(fb, x + i, y + j, color);
            }
        }
    }
}

void lcd_polyline(u32 fb, const int *pts, int npts, u16 color)
{
    int i;
    if (pts == 0 || npts < 2) {
        return;
    }
    for (i = 0; i < npts - 1; i++) {
        lcd_line(fb, pts[2 * i], pts[2 * i + 1],
                 pts[2 * i + 2], pts[2 * i + 3], color);
    }
}

void lcd_plot(u32 fb, int x0, int x1, int y_center, s32 yscale,
              lcd_fn_t fn, void *ctx, u16 color)
{
    int  x, px = 0;
    s32  py = 0;
    s32  yv;
    int  first = 1;

    if (fn == 0) {
        return;
    }
    if (x1 < x0) {
        int t = x0; x0 = x1; x1 = t;
    }
    for (x = x0; x <= x1; x++) {
        yv = sat_s64((s64)fn((s32)x, ctx) * (s64)yscale);
        yv = sat_s64((s64)y_center - (s64)yv);
        if (first) {
            px_put(fb, x, (int)yv, color);
            first = 0;
        } else {
            lcd_line(fb, px, (int)py, x, (int)yv, color);
        }
        px = x;
        py = yv;
    }
}

void lcd_bezier2(u32 fb, int x0, int y0, int x1, int y1, int x2, int y2,
                 u16 color, int steps)
{
    int  i, bx = x0, by = y0, nx, ny;
    s64  nn, tt;

    if (steps < 1) {
        steps = 1;
    }
    if (steps > 4096) {
        steps = 4096;
    }
    for (i = 1; i <= steps; i++) {
        tt = i;
        nn = steps - i;
        nx = (int)sat_s64((nn * nn * (s64)x0 + 2 * nn * tt * (s64)x1 +
                           tt * tt * (s64)x2) / ((s64)steps * steps));
        ny = (int)sat_s64((nn * nn * (s64)y0 + 2 * nn * tt * (s64)y1 +
                           tt * tt * (s64)y2) / ((s64)steps * steps));
        lcd_line(fb, bx, by, nx, ny, color);
        bx = nx;
        by = ny;
    }
}

