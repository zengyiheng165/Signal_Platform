int lcd_char(u32 fb, int x, int y, char ch, u16 color, u8 scale)
{
    u32        idx = (u32)(u8)ch;
    const u8  *g;
    int        row, col, sx, sy;

    if (scale == 0) {
        scale = 1;
    }
    if (idx >= 128u) {
        idx = 63u;   /* '?' */
    }
    g = lcd_font8x8[idx];

    for (row = 0; row < 8; row++) {
        for (col = 0; col < 8; col++) {
            if (g[row] & (1u << col)) {
                for (sy = 0; sy < scale; sy++) {
                    for (sx = 0; sx < scale; sx++) {
                        px_put(fb, x + col * (int)scale + sx,
                               y + row * (int)scale + sy, color);
                    }
                }
            }
        }
    }
    return 8 * (int)scale;
}

int lcd_text(u32 fb, int x, int y, const char *s, u16 color, u8 scale)
{
    const char *p = s;
    while (p && *p) {
        if (*p != '\r' && *p != '\n') {
            x += lcd_char(fb, x, y, *p, color, scale);
        }
        p++;
    }
    return x;
}

int lcd_text_bg(u32 fb, int x, int y, const char *s,
                u16 color, u16 bg, u8 scale)
{
    const char *p = s;
    while (p && *p) {
        if (*p != '\r' && *p != '\n') {
            lcd_fill_rect(fb, x, y, 8 * (int)scale, 8 * (int)scale, bg);
            x += lcd_char(fb, x, y, *p, color, scale);
        }
        p++;
    }
    return x;
}

u32 lcd_text_width(const char *s, u8 scale)
{
    if (scale == 0) {
        scale = 1;
    }
    return (u32)strlen(s) * 8u * scale;
}

int lcd_int(u32 fb, int x, int y, s32 value, u16 color, u8 scale)
{
    char buf[12];
    int  i = 11;
    int  neg = 0;
    u32  v;

    buf[11] = '\0';
    if (value < 0) {
        neg = 1;
        v = (u32)(-(value + 1)) + 1u;   /* 先转正, 规避 INT32_MIN */
    } else {
        v = (u32)value;
    }

    if (v == 0) {
        buf[--i] = '0';
    }
    while (v > 0) {
        buf[--i] = (char)('0' + (v % 10u));
        v /= 10u;
    }
    if (neg) {
        buf[--i] = '-';
    }
    return lcd_text(fb, x, y, &buf[i], color, scale);
}

int lcd_uint(u32 fb, int x, int y, u32 value, u16 color, u8 scale)
{
    char buf[11];
    int  i = 10;
    buf[10] = '\0';
    if (value == 0) {
        buf[--i] = '0';
    }
    while (value > 0) {
        buf[--i] = (char)('0' + (value % 10u));
        value /= 10u;
    }
    return lcd_text(fb, x, y, &buf[i], color, scale);
}

int lcd_hex(u32 fb, int x, int y, u32 value, u16 color, u8 scale)
{
    static const char hx[] = "0123456789ABCDEF";
    char buf[11];
    int  i = 10;
    buf[10] = '\0';
    if (value == 0) {
        buf[--i] = '0';
    }
    while (value > 0) {
        buf[--i] = hx[value & 0xFu];
        value >>= 4;
    }
    return lcd_text(fb, x, y, &buf[i], color, scale);
}
